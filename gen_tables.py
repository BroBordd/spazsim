"""Extract the game's baked 'precalc rands' tables (shared/generic/utils.cc)
into a C header so the headless sim uses the very same numbers."""
import re, sys
src = open(sys.argv[1]).read()
out = ["// generated by gen_tables.py from ballistica utils.cc", "#pragma once"]
for n in (1, 2, 3):
    m = re.search(r"precalc_rands_%d_\[kPrecalcRandsCount\] = \{(.*?)\};" % n, src, re.S)
    vals = [v.strip() for v in m.group(1).replace("\n", " ").split(",") if v.strip()]
    assert len(vals) == 128, (n, len(vals))
    out.append("static const float kPrecalc%d[128] = {%s};" % (n, ", ".join(vals)))
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print("ok")
